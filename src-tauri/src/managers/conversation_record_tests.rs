#[test]
fn sanitize_caps_user_on_char_boundary_with_marker() {
    // Multi-byte chars make a byte-based cut panic or split a char.
    let long = "\u{e9}".repeat(MAX_SIDE_CHARS + 300);
    // [needs redact]: sanitize_turn calls redact on every side.
    let rec = sanitize_turn(
        &long,
        None,
        TurnOutcomeLabel::Answered,
        DeliveryLabel::Submitted,
        None,
    );
    assert!(
        rec.user.ends_with(TRUNC),
        "missing visible truncation marker"
    );
    let kept = rec.user.strip_suffix(TRUNC).expect("marker suffix");
    let n = kept.chars().count();
    assert!(
        n > 0 && n <= MAX_SIDE_CHARS,
        "kept {n} chars, cap is {MAX_SIDE_CHARS}"
    );
    assert!(
        kept.chars().all(|c| c == '\u{e9}'),
        "cut must keep whole chars"
    );
}

