fn ms(rfc3339: &str) -> i64 {
    chrono::DateTime::parse_from_rfc3339(rfc3339)
        .expect("valid rfc3339 fixture")
        .timestamp_millis()
}

fn turn(user: &str, assistant: Option<&str>) -> TurnRecord {
    TurnRecord {
        user: user.to_string(),
        assistant: assistant.map(str::to_string),
        outcome: TurnOutcomeLabel::Answered,
        delivery: DeliveryLabel::Submitted,
        detail: None,
    }
}

fn session(turns: Vec<TurnRecord>, summary: Option<&str>) -> SessionRecord {
    SessionRecord {
        started_at_ms: ms("2026-03-14T09:05:00Z"),
        ended_at_ms: ms("2026-03-14T09:07:30Z"),
        end: EndLabel::UserEnded,
        turns,
        summary: summary.map(str::to_string),
    }
}

fn longest_run(s: &str, c: char) -> usize {
    let mut best = 0;
    let mut cur = 0;
    for ch in s.chars() {
        if ch == c {
            cur += 1;
            best = best.max(cur);
        } else {
            cur = 0;
        }
    }
    best
}

#[derive(Default)]
struct Doc {
    /// Lines outside any fenced block (live Markdown and frontmatter).
    outside: Vec<String>,
    /// Fenced blocks: fence length and joined content.
    blocks: Vec<Block>,
    /// Fence openers that were not `text` fences, or unclosed fences.
    bad_fences: usize,
}

struct Block {
    fence: usize,
    content: String,
}

/// Splits a rendered note into live lines and `text`-fenced blocks.
fn scan(doc: &str) -> Doc {
    let mut out = Doc::default();
    let mut open: Option<(usize, Vec<&str>)> = None;
    for line in doc.split('\n') {
        if let Some((n, mut lines)) = open.take() {
            if line.len() == n && line.chars().all(|c| c == '`') {
                out.blocks.push(Block {
                    fence: n,
                    content: lines.join("\n"),
                });
            } else {
                lines.push(line);
                open = Some((n, lines));
            }
            continue;
        }
        let ticks = line.chars().take_while(|c| *c == '`').count();
        if ticks >= 3 {
            if &line[ticks..] == "text" {
                open = Some((ticks, Vec::new()));
            } else {
                out.bad_fences += 1;
                out.outside.push(line.to_string());
            }
            continue;
        }
        out.outside.push(line.to_string());
    }
    if open.is_some() {
        out.bad_fences += 1;
    }
    out
}

fn is_machine_heading(line: &str) -> bool {
    line == "## Summary"
        || line == "## Transcript"
        || line
            .strip_prefix("### Turn ")
            .is_some_and(|n| !n.is_empty() && n.chars().all(|c| c.is_ascii_digit()))
}

/// Asserts the whole-note invariants: one frontmatter block with only the
/// whitelisted keys, machine-only headings, the banner, and balanced fences.
fn check_doc(doc: &str) -> Doc {
    let d = scan(doc);
    assert_eq!(d.bad_fences, 0, "unbalanced or non-text fence in note");
    assert!(doc.starts_with("---\n"), "frontmatter must start the file");
    assert!(!doc.contains('\0'), "NUL leaked into note");
    assert!(!doc.contains('\r'), "CR leaked into note");

    let closers: Vec<usize> = d
        .outside
        .iter()
        .enumerate()
        .filter(|(_, l)| *l == "---")
        .map(|(i, _)| i)
        .collect();
    assert_eq!(
        closers.len(),
        2,
        "exactly one frontmatter block outside fences"
    );
    assert_eq!(closers[0], 0, "frontmatter opener must be line 1");

    let mut keys: Vec<&str> = Vec::new();
    for line in &d.outside[1..closers[1]] {
        let (k, v) = line
            .split_once(": ")
            .unwrap_or_else(|| panic!("frontmatter line not key: value: {line:?}"));
        assert!(FRONTMATTER_KEYS.contains(&k), "non-whitelisted key {k:?}");
        assert!(
            v.chars()
                .all(|c| c.is_ascii_alphanumeric() || "-:._+".contains(c)),
            "frontmatter value not YAML-safe: {v:?}"
        );
        keys.push(k);
    }
    keys.sort_unstable();
    let mut want = FRONTMATTER_KEYS.to_vec();
    want.sort_unstable();
    assert_eq!(keys, want, "frontmatter must contain exactly the whitelist");

    for line in &d.outside {
        if line.starts_with('#') {
            assert!(
                is_machine_heading(line),
                "untrusted heading leaked: {line:?}"
            );
        }
    }
    assert!(
        d.outside.join("\n").contains(BANNER),
        "banner text missing from note"
    );
    d
}

/// Asserts `fragment` is inside a `text` fence longer than its longest backtick run.
fn assert_fenced(d: &Doc, fragment: &str) {
    let longest = longest_run(fragment, '`');
    let block = d
        .blocks
        .iter()
        .find(|b| b.content.contains(fragment))
        .unwrap_or_else(|| panic!("fragment not inside a text fence: {fragment:?}"));
    assert!(
        block.fence >= 3 && block.fence > longest,
        "fence {} not longer than backtick run {} for {fragment:?}",
        block.fence,
        longest
    );
}

/// Asserts no live token from `fragment` appears outside every fence.
fn assert_not_live(d: &Doc, fragment: &str) {
    let outside = d.outside.join("\n");
    for tok in LIVE_TOKENS {
        if fragment.contains(tok) {
            assert!(
                !outside.contains(tok),
                "live token {tok:?} from {fragment:?} leaked outside a fence"
            );
        }
    }
}

fn shown_turns(d: &Doc) -> Vec<usize> {
    d.outside
        .iter()
        .filter_map(|l| l.strip_prefix("### Turn "))
        .map(|n| n.parse::<usize>().expect("turn heading number"))
        .collect()
}

