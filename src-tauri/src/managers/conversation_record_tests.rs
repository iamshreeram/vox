fn is_lower_hex8(id: &str) -> bool {
    id.len() == 8
        && id
            .chars()
            .all(|c| c.is_ascii_digit() || ('a'..='f').contains(&c))
}

#[test]
fn id8_is_eight_lowercase_hex() {
    let id = session_id8(ms("2026-03-14T09:05:00Z"), &[turn("hi", None)]);
    assert!(is_lower_hex8(&id), "not 8 lowercase hex: {id:?}");
}

