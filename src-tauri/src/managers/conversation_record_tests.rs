fn budget_session(unit: &str) -> SessionRecord {
    let turns: Vec<TurnRecord> = (0..MAX_TURNS).map(|_| turn(unit, Some(unit))).collect();
    session(turns, Some(&"s".repeat(800)))
}

/// Checks the budget invariants for a maximal session: the note fits the cap,
/// the omission count is correct, and the kept turns are the newest ones.
fn check_budget(rec: &SessionRecord) {
    let doc = render_markdown(rec, SID);
    assert!(
        doc.len() <= MAX_NOTE_BYTES,
        "note is {} bytes, cap is {MAX_NOTE_BYTES}",
        doc.len()
    );
    let d = check_doc(&doc);
    let shown = shown_turns(&d);
    let omitted = MAX_TURNS - shown.len();
    assert!(omitted > 0, "max session must omit turns to fit the budget");
    assert_eq!(
        shown,
        (omitted + 1..=MAX_TURNS).collect::<Vec<_>>(),
        "kept turns must be the newest contiguous suffix"
    );
    let line = format!("_{omitted} {OMIT_TAIL}");
    assert!(
        d.outside.iter().any(|l| l == &line),
        "missing omission line {line:?}"
    );
}

