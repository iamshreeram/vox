//! NeMo-compatible log-mel front end for the IndicConformer encoder.
//!
//! Mirrors the TorchScript `AudioToMelSpectrogramPreprocessor` shipped with the pack
//! (`assets/preprocessor.ts`): pre-emphasis 0.97, reflect padding of 256 samples per side,
//! STFT with n_fft 512, hop 160, a 400-sample symmetric Hann window zero padded to 512,
//! power spectrum, a 257x80 Slaney mel filterbank, `log(x + 2^-24)` and per-band
//! normalisation over the valid frames with an unbiased variance. Frames are
//! `floor(N / 160) + 1`. The goldens live in `tests/fixtures/tamil_stt/mel_golden.json`.

