/// Log-mel features for one chunk of 16 kHz mono audio.
#[derive(Debug, Clone, PartialEq)]
pub struct MelFeatures {
    /// Row-major `[N_MELS, frames]` (band major), normalised per band.
    pub data: Vec<f32>,
    /// Number of time frames.
    pub frames: usize,
}

/// Mel front end (window and filterbank are built once in `new`).
#[derive(Clone)]
pub struct MelFrontend {
    /// Symmetric Hann window, 400 samples.
    window: Vec<f32>,
    /// Filterbank, bin-major `[257, N_MELS]` (`filterbank[k * N_MELS + band]`).
    filterbank: Vec<f32>,
    /// Forward FFT plan of size `N_FFT` (f64), built once.
    fft: Arc<dyn Fft<f64>>,
}

impl fmt::Debug for MelFrontend {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("MelFrontend")
            .field("window_len", &self.window.len())
            .field("filterbank_len", &self.filterbank.len())
            .finish()
    }
}

/// Padding used at both ends of the signal before the STFT.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum PadMode {
    /// Mirror the signal (the NeMo behaviour).
    Reflect,
    /// Zero padding (mutation check only).
    #[cfg_attr(not(test), allow(dead_code))]
    Zero,
}

/// Mel scale used to place the filterbank (formula path, tests only).
#[cfg(test)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum MelScale {
    /// Slaney scale (the NeMo and librosa default).
    Slaney,
    /// HTK scale (mutation check only).
    Htk,
}

/// Symmetric (`periodic == false`) or periodic Hann window of length 400.
pub(crate) fn hann_window(periodic: bool) -> Vec<f32> {
    let denom = (if periodic { WIN_LENGTH } else { WIN_LENGTH - 1 }) as f64;
    (0..WIN_LENGTH)
        .map(|n| (0.5 - 0.5 * (2.0 * std::f64::consts::PI * n as f64 / denom).cos()) as f32)
        .collect()
}

/// Mel filterbank, bin-major `[257, N_MELS]`, slaney-normalised, built from the formula.
#[cfg(test)]
pub(crate) fn mel_filterbank(scale: MelScale) -> Vec<f32> {
    let f_max = SAMPLE_RATE_HZ / 2.0;
    let fft_freqs: Vec<f64> = (0..N_BINS)
        .map(|k| k as f64 * f_max / (N_BINS - 1) as f64)
        .collect();
    let mel_lo = hz_to_mel(0.0, scale);
    let mel_hi = hz_to_mel(f_max, scale);
    let hz_pts: Vec<f64> = (0..N_MELS + 2)
        .map(|i| {
            mel_to_hz(
                mel_lo + (mel_hi - mel_lo) * i as f64 / (N_MELS + 1) as f64,
                scale,
            )
        })
        .collect();

    let mut fb = vec![0.0_f32; N_BINS * N_MELS];
    for band in 0..N_MELS {
        let (lo, mid, hi) = (hz_pts[band], hz_pts[band + 1], hz_pts[band + 2]);
        let enorm = 2.0 / (hi - lo);
        for (k, &freq) in fft_freqs.iter().enumerate() {
            let rising = (freq - lo) / (mid - lo);
            let falling = (hi - freq) / (hi - mid);
            let weight = rising.min(falling).max(0.0) * enorm;
            fb[k * N_MELS + band] = weight as f32;
        }
    }
    fb
}

/// Hz to mel on the requested scale.
#[cfg(test)]
fn hz_to_mel(hz: f64, scale: MelScale) -> f64 {
    match scale {
        MelScale::Htk => 2595.0 * (1.0 + hz / 700.0).log10(),
        MelScale::Slaney => {
            let (f_sp, min_log_hz, min_log_mel, logstep) = slaney_consts();
            if hz >= min_log_hz {
                min_log_mel + (hz / min_log_hz).ln() / logstep
            } else {
                hz / f_sp
            }
        }
    }
}

/// Mel to Hz on the requested scale (inverse of [`hz_to_mel`]).
#[cfg(test)]
fn mel_to_hz(mel: f64, scale: MelScale) -> f64 {
    match scale {
        MelScale::Htk => 700.0 * (10f64.powf(mel / 2595.0) - 1.0),
        MelScale::Slaney => {
            let (f_sp, min_log_hz, min_log_mel, logstep) = slaney_consts();
            if mel >= min_log_mel {
                min_log_hz * (logstep * (mel - min_log_mel)).exp()
            } else {
                f_sp * mel
            }
        }
    }
}

/// Constants of the Slaney mel scale: (f_sp, min_log_hz, min_log_mel, logstep).
#[cfg(test)]
fn slaney_consts() -> (f64, f64, f64, f64) {
    let f_sp = 200.0 / 3.0;
    let min_log_hz = 1000.0;
    (f_sp, min_log_hz, min_log_hz / f_sp, 6.4_f64.ln() / 27.0)
}

/// Dense `[257, N_MELS]` filterbank (bin-major) from the shipped span table.
fn shipped_filterbank() -> Vec<f32> {
    let mut fb = vec![0.0_f32; N_BINS * N_MELS];
    for (band, (first, weights)) in SLANEY_FILTERBANK.iter().enumerate() {
        for (offset, &w) in weights.iter().enumerate() {
            if let Some(cell) = fb.get_mut((first + offset) * N_MELS + band) {
                *cell = w;
            }
        }
    }
    fb
}

/// Pre-emphasis `y[0] = x[0]`, `y[t] = x[t] - 0.97 * x[t-1]`.
fn preemphasis(x: &[f32]) -> Vec<f32> {
    let mut out = Vec::with_capacity(x.len());
    let mut prev = 0.0_f32;
    for &v in x {
        out.push(v - PREEMPH * prev);
        prev = v;
    }
    out
}

/// Pad `x` by `PAD` samples on each side (reflect or zero).
fn pad_signal(x: &[f32], pad: PadMode) -> Vec<f32> {
    let n = x.len() as isize;
    let total = x.len() + 2 * PAD;
    (0..total)
        .map(|p| {
            let i = p as isize - PAD as isize;
            if (0..n).contains(&i) {
                return x.get(i as usize).copied().unwrap_or(0.0);
            }
            match pad {
                PadMode::Zero => 0.0,
                PadMode::Reflect => {
                    let j = if i < 0 { -i } else { 2 * (n - 1) - i };
                    x.get(j as usize).copied().unwrap_or(0.0)
                }
            }
        })
        .collect()
}

impl MelFrontend {
    /// Build the front end with the NeMo window and the Slaney filterbank.
    pub fn new() -> Self {
        let mut planner = FftPlanner::<f64>::new();
        Self {
            window: hann_window(false),
            filterbank: shipped_filterbank(),
            fft: planner.plan_fft_forward(N_FFT),
        }
    }

    /// Build a front end from an explicit window (400 samples) and filterbank (257 * 80,
    /// bin-major). Used by the tests to check that deliberate changes fail the golden.
    #[cfg(test)]
    pub(crate) fn from_parts(window: Vec<f32>, filterbank: Vec<f32>) -> Result<Self, String> {
        if window.len() != WIN_LENGTH {
            return Err(format!(
                "window must have {WIN_LENGTH} samples, got {}",
                window.len()
            ));
        }
        if filterbank.len() != N_BINS * N_MELS {
            return Err(format!(
                "filterbank must have {} values, got {}",
                N_BINS * N_MELS,
                filterbank.len()
            ));
        }
        let mut planner = FftPlanner::<f64>::new();
        Ok(Self {
            window,
            filterbank,
            fft: planner.plan_fft_forward(N_FFT),
        })
    }

    /// Window used by this front end.
    #[cfg(test)]
    pub(crate) fn window(&self) -> &[f32] {
        &self.window
    }

    /// Filterbank used by this front end (bin-major `[257, N_MELS]`).
    #[cfg(test)]
    pub(crate) fn filterbank(&self) -> &[f32] {
        &self.filterbank
    }

    /// Compute features with an explicit padding mode. Skips the public minimum length of 400
    /// samples but still requires more than 256 samples and finite input.
    pub(crate) fn compute(&self, samples: &[f32], pad: PadMode) -> Result<MelFeatures, String> {
        let n = samples.len();
        if n < MIN_INTERNAL_SAMPLES {
            return Err(format!("audio too short: {n} samples"));
        }
        if samples.iter().any(|v| !v.is_finite()) {
            return Err("audio contains a non-finite sample".to_string());
        }
        let frames = n / HOP + 1;
        let padded = pad_signal(&preemphasis(samples), pad);

        let mut wpad = vec![0.0_f64; N_FFT];
        for (dst, &w) in wpad[WIN_OFFSET..WIN_OFFSET + WIN_LENGTH]
            .iter_mut()
            .zip(&self.window)
        {
            *dst = f64::from(w);
        }
        let mut buf = vec![Complex::new(0.0_f64, 0.0_f64); N_FFT];
        let mut scratch = vec![Complex::new(0.0_f64, 0.0_f64); self.fft.get_inplace_scratch_len()];
        let mut acc = vec![0.0_f64; N_MELS];
        let mut logmel = vec![0.0_f64; N_MELS * frames];

        for t in 0..frames {
            let start = t * HOP;
            let segment = padded
                .get(start..start + N_FFT)
                .ok_or_else(|| "internal: frame out of range".to_string())?;
            for ((dst, &s), &w) in buf.iter_mut().zip(segment).zip(&wpad) {
                *dst = Complex::new(f64::from(s) * w, 0.0);
            }
            self.fft.process_with_scratch(&mut buf, &mut scratch);

            acc.iter_mut().for_each(|a| *a = 0.0);
            for (k, c) in buf.iter().take(N_BINS).enumerate() {
                let power = c.re.powi(2) + c.im.powi(2);
                let row = &self.filterbank[k * N_MELS..(k + 1) * N_MELS];
                for (a, &w) in acc.iter_mut().zip(row) {
                    *a += f64::from(w) * power;
                }
            }
            for (band, &a) in acc.iter().enumerate() {
                logmel[band * frames + t] = (a + LOG_GUARD).ln();
            }
        }

        let mut data = vec![0.0_f32; N_MELS * frames];
        let denom_frames = (frames - 1) as f64;
        for (row, out) in logmel
            .chunks_exact(frames)
            .zip(data.chunks_exact_mut(frames))
        {
            let mean = row.iter().sum::<f64>() / frames as f64;
            let var = row.iter().map(|&v| (v - mean).powi(2)).sum::<f64>() / denom_frames;
            let std = var.max(VAR_FLOOR).sqrt();
            for (dst, &v) in out.iter_mut().zip(row) {
                *dst = ((v - mean) / (std + NORM_EPS)) as f32;
            }
        }
        Ok(MelFeatures { data, frames })
    }

    /// Compute features for 16 kHz mono samples.
    ///
    /// Returns `Err` for fewer than 400 samples (the caller drops audio shorter than 0.1 s
    /// earlier) and for any non-finite sample. Returns `frames = floor(N / 160) + 1` frames of
    /// 80 bands each, band major.
    pub fn features(&self, samples: &[f32]) -> Result<MelFeatures, String> {
        if samples.len() < MIN_SAMPLES {
            return Err(format!(
                "audio too short: {} samples, need at least {MIN_SAMPLES}",
                samples.len()
            ));
        }
        self.compute(samples, PadMode::Reflect)
    }
}

impl Default for MelFrontend {
    fn default() -> Self {
        Self::new()
    }
}
